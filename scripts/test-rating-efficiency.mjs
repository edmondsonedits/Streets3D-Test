import assert from 'node:assert/strict';
import {calculateTotal, calculateVisualScore, costPer100Metres, storageCostPer100Metres, rankRatings} from '../site/ratings-core.mjs';
const rubric=Array.from({length:10},(_,i)=>({id:'c'+i,weight:10,dimension:i<5?'visual':'efficiency'}));
const all=rubric.map(x=>({category:x.id,score:10}));
assert.equal(calculateTotal(all,rubric),100);
assert.equal(calculateTotal(all.map(x=>({...x,score:0})),rubric),0);
assert.equal(calculateTotal(all.map((x,i)=>i<5?x:{...x,score:null}),rubric),null,'missing evidence must not earn neutral points');
assert.equal(calculateVisualScore(all.map((x,i)=>i<5?x:{...x,score:null}),rubric),100,'visual score independent of missing costs');
assert.equal(calculateVisualScore(all.map((x,i)=>i===0?{...x,score:null}:x),rubric),null,'missing visual evidence must not silently renormalize');
assert.throws(()=>calculateTotal(all.slice(1),rubric),/Missing/i);
assert.throws(()=>calculateTotal([...all,all[0]],rubric),/Duplicate/i);
assert.throws(()=>calculateTotal(all.map((x,i)=>i?x:{...x,score:NaN}),rubric));
assert.throws(()=>calculateTotal(all.map((x,i)=>i?x:{...x,score:11}),rubric));
assert.equal(storageCostPer100Metres(500e6,1000),50);
assert.equal(storageCostPer100Metres(200e6,500),40);
assert.ok(Math.abs(1-storageCostPer100Metres(200e6,500)/storageCostPer100Metres(500e6,1000)-.2)<1e-12,'half street at 200MB uses 20% less per metre');
assert.equal(storageCostPer100Metres(1000e6,2000),50,'doubling equal-quality coverage and bytes preserves efficiency');
assert.equal(storageCostPer100Metres(1e6,null),null);
assert.equal(storageCostPer100Metres(1e6,0),null,'zero accepted coverage cannot win on tiny size');
assert.equal(costPer100Metres(null,100),null);
assert.equal(costPer100Metres(60,200),30);
assert.throws(()=>storageCostPer100Metres(1e6,-1));
const tied=rankRatings([{id:'b',visualScore:60,total:null},{id:'c',visualScore:50,total:null},{id:'a',visualScore:60,total:null}]);
assert.deepEqual(tied.map(x=>[x.id,x.rank]),[['a',1],['b',1],['c',3]]);
console.log('PASS normalized coverage cost, missing evidence and visual-only ranking');
